import torch
import torch.nn as nn
import torch.nn.functional as F
import logging

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(message)s')

class DoubleConv(nn.Module):
    """(Convolution => [BatchNorm] => ReLU) * 2"""
    def __init__(self, in_channels, out_channels):
        super().__init__()
        self.double_conv = nn.Sequential(
            nn.Conv2d(in_channels, out_channels, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_channels, out_channels, kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(out_channels),
            nn.ReLU(inplace=True)
        )

    def forward(self, x):
        return self.double_conv(x)

class Down(nn.Module):
    """Downscaling with MaxPool2d then DoubleConv"""
    def __init__(self, in_channels, out_channels):
        super().__init__()
        self.maxpool_conv = nn.Sequential(
            nn.MaxPool2d(2),
            DoubleConv(in_channels, out_channels)
        )

    def forward(self, x):
        return self.maxpool_conv(x)

class Up(nn.Module):
    """Upscaling then DoubleConv"""
    def __init__(self, in_channels, out_channels):
        super().__init__()
        # Using bilinear upsampling to save VRAM and increase Scout speed
        self.up = nn.Upsample(scale_factor=2, mode='bilinear', align_corners=True)
        self.conv = DoubleConv(in_channels, out_channels)

    def forward(self, x1, x2):
        x1 = self.up(x1)
        # Handle spatial padding if grid dimensions don't divide perfectly
        diffY = x2.size()[2] - x1.size()[2]
        diffX = x2.size()[3] - x1.size()[3]
        
        x1 = F.pad(x1, [diffX // 2, diffX - diffX // 2,
                        diffY // 2, diffY - diffY // 2])
        
        x = torch.cat([x2, x1], dim=1)
        return self.conv(x)

class BasicUNetScout(nn.Module):
    """
    Lightweight U-Net acting as the Scout.
    Input: 1-Channel SAR Image (Grayscale 512x512 tile)
    Output: 1-Channel Probability Logits (Oil Anomaly)
    """
    def __init__(self, n_channels=1, n_classes=1):
        super(BasicUNetScout, self).__init__()
        self.n_channels = n_channels
        self.n_classes = n_classes

        # Scaled-down channel architecture (16 -> 256) for high-throughput inference
        self.inc = DoubleConv(n_channels, 16)
        self.down1 = Down(16, 32)
        self.down2 = Down(32, 64)
        self.down3 = Down(64, 128)
        self.down4 = Down(128, 256)
        
        # Skip connections require adding encoder and decoder channels
        self.up1 = Up(256 + 128, 128)
        self.up2 = Up(128 + 64, 64)
        self.up3 = Up(64 + 32, 32)
        self.up4 = Up(32 + 16, 16)
        
        self.outc = nn.Conv2d(16, n_classes, kernel_size=1)

    def forward(self, x):
        x1 = self.inc(x)
        x2 = self.down1(x1)
        x3 = self.down2(x2)
        x4 = self.down3(x3)
        x5 = self.down4(x4)
        
        x = self.up1(x5, x4)
        x = self.up2(x, x3)
        x = self.up3(x, x2)
        x = self.up4(x, x1)
        
        logits = self.outc(x)
        return logits

def evaluate_scout_flag(logits: torch.Tensor, threshold_ratio: float = 0.01) -> bool:
    """
    Applies Sigmoid to logits and checks if enough pixels are flagged 
    to trigger the Swin-UNet Sniper model.
    """
    probs = torch.sigmoid(logits)
    binary_mask = (probs > 0.5).float()
    
    anomalous_pixels = torch.sum(binary_mask).item()
    total_pixels = binary_mask.numel()
    
    # If anomalous footprint > 1% of the chip, trigger sniper
    if (anomalous_pixels / total_pixels) >= threshold_ratio:
        return True
    return False

